def kabsch(P: np.ndarray, Q: np.ndarray) -> Tuple[np.ndarray, np.ndarray, float]:
    """Return (R, t, rmsd) minimizing ||(R P + t) - Q|| for corresponding point sets.

    P, Q: (N,3)
    """
    if P.shape != Q.shape or P.ndim != 2 or P.shape[1] != 3:
        raise ValueError(f"Kabsch: bad shapes P={P.shape}, Q={Q.shape}")

    Pc = P.mean(axis=0)
    Qc = Q.mean(axis=0)
    P0 = P - Pc
    Q0 = Q - Qc
    H = P0.T @ Q0
    U, S, Vt = np.linalg.svd(H)
    R = Vt.T @ U.T
    if np.linalg.det(R) < 0:
        Vt[-1, :] *= -1
        R = Vt.T @ U.T
    t = Qc - R @ Pc
    Pfit = (R @ P.T).T + t
    rmsd = float(np.sqrt(np.mean(np.sum((Pfit - Q) ** 2, axis=1))))
    return R, t, rmsd


def rotation_matrix_from_vectors(v_from: np.ndarray, v_to: np.ndarray) -> np.ndarray:
    """Minimal rotation that maps v_from to v_to (both 3D)."""
    v1 = v_from / np.linalg.norm(v_from)
    v2 = v_to / np.linalg.norm(v_to)
    c = float(np.dot(v1, v2))
    # Clamp for numeric stability
    c = max(-1.0, min(1.0, c))

    if c > 0.999999:
        return np.eye(3)

    if c < -0.999999:
        # 180 degree rotation around any axis orthogonal to v1
        # Pick a stable orthogonal axis.
        ortho = np.array([1.0, 0.0, 0.0])
        if abs(v1[0]) > 0.9:
            ortho = np.array([0.0, 1.0, 0.0])
        axis = np.cross(v1, ortho)
        axis = axis / np.linalg.norm(axis)
        return rodrigues(axis, math.pi)

    axis = np.cross(v1, v2)
    s = np.linalg.norm(axis)
    axis = axis / s
    angle = math.atan2(s, c)
    return rodrigues(axis, angle)


def rodrigues(axis: np.ndarray, angle: float) -> np.ndarray:
    """Rodrigues' rotation formula for unit axis."""
    ax = axis / np.linalg.norm(axis)
    K = np.array(
        [[0.0, -ax[2], ax[1]], [ax[2], 0.0, -ax[0]], [-ax[1], ax[0], 0.0]], dtype=float
    )
    I = np.eye(3)
    return I + math.sin(angle) * K + (1.0 - math.cos(angle)) * (K @ K)


def apply_rigid_transform(records: List[object], R: np.ndarray, t: np.ndarray) -> None:
    """In-place rigid transform of all ATOM/HETATM records."""
    for rec in records:
        if _is_atom_record(rec):
            xyz = np.array([rec.x, rec.y, rec.z], dtype=float)
            new = R @ xyz + t
            rec.update_xyz(float(new[0]), float(new[1]), float(new[2]))


def apply_rotation_about_point(records: List[object], R: np.ndarray, pivot: np.ndarray) -> None:
    """In-place rotation of all ATOM/HETATM records about a pivot point."""
    for rec in records:
        if _is_atom_record(rec):
            xyz = np.array([rec.x, rec.y, rec.z], dtype=float)
            new = R @ (xyz - pivot) + pivot
            rec.update_xyz(float(new[0]), float(new[1]), float(new[2]))


def apply_translation(records: List[object], shift: np.ndarray) -> None:
    """In-place translation of all ATOM/HETATM records."""

    for rec in records:
        if _is_atom_record(rec):
            rec.update_xyz(float(rec.x + shift[0]), float(rec.y + shift[1]), float(rec.z + shift[2]))


def axis_line_distance(p1: np.ndarray, u: np.ndarray, p2: np.ndarray, v: np.ndarray) -> float:
    """Shortest distance between two 3D lines p1+t*u and p2+s*v."""

    u = u / np.linalg.norm(u)
    v = v / np.linalg.norm(v)
    w = p2 - p1
    c = np.cross(u, v)
    nc = float(np.linalg.norm(c))
    if nc < 1e-10:
        return float(np.linalg.norm(w - np.dot(w, u) * u))
    return float(abs(np.dot(w, c / nc)))


def perpendicular_shift_to_collinear(fixed_point: np.ndarray, fixed_dir: np.ndarray, moving_point: np.ndarray) -> np.ndarray:
    """Return a pure lateral shift that puts the moving axis point on the fixed axis line."""

    u = fixed_dir / np.linalg.norm(fixed_dir)
    delta = fixed_point - moving_point
    return delta - np.dot(delta, u) * u




