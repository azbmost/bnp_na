ResidKey = Tuple[str, str, int]  # (seg_id, chainID, resSeq)


@dataclass
class Residue:
    key: ResidKey
    chainID: str
    resSeq: int
    resName: str
    atoms: List[pdb_atom_record]
    atom_by_name: Dict[str, pdb_atom_record]

    def xyz(self, atom_name: str) -> Optional[np.ndarray]:
        """Return xyz for a requested atom name (with alias support), else None."""
        aliases = _ATOM_NAME_ALIASES.get(atom_name, [atom_name])
        for nm in aliases:
            rec = self.atom_by_name.get(nm)
            if rec is not None:
                return np.array([rec.x, rec.y, rec.z], dtype=float)
        return None


@dataclass
class Structure:
    name: str
    seg_id: str
    records: List[object]  # pdb_atom_record | pdb_ter_record
    residues: Dict[ResidKey, Residue]
    chains: List[str]  # chosen two main chain IDs, in internal order
    basepairs: List[Tuple[ResidKey, ResidKey]]  # physical order start->end

    # Which physical end was used to connect to the *previous* junction:
    #   'start' or 'end'.
    # For the first helix we set backward_end='start' so the default forward connection uses 'end'.
    backward_end: str = 'start'

    # Residues to delete at the end (overlaps with core)
    trim: set = None

    # Residues removed during input preprocessing (currently used for Z-DNA
    # terminal phase correction). These are excluded from alignment, raw output,
    # and final output.
    pre_trim: set = None

    def __post_init__(self):
        if self.trim is None:
            self.trim = set()
        if self.pre_trim is None:
            self.pre_trim = set()

    def forward_end(self) -> str:
        return 'end' if self.backward_end == 'start' else 'start'

    def _end_indices(self, end: str, n_bp: int = 2) -> List[int]:
        if len(self.basepairs) < n_bp:
            raise ValueError(f"{self.name}: need at least {n_bp} basepairs, found {len(self.basepairs)}")
        if end == 'end':
            # interior -> outer already
            return list(range(len(self.basepairs) - n_bp, len(self.basepairs)))
        if end == 'start':
            # basepairs[0] is outermost at start; return interior->outer
            return list(reversed(range(0, n_bp)))
        raise ValueError(f"end must be 'start' or 'end', got {end}")

    def end_basepairs(self, end: str, n_bp: int = 2) -> List[Tuple[ResidKey, ResidKey]]:
        idxs = self._end_indices(end, n_bp=n_bp)
        return [self.basepairs[i] for i in idxs]

    def axis_line(self, extra_exclude: Optional[set] = None) -> Tuple[np.ndarray, np.ndarray]:
        """Estimate helical axis line by PCA on active C1' atoms.

        Returns ``(point, direction)``, where ``point`` is the centroid of active
        C1' atoms and ``direction`` is a unit vector along the best-fit line.
        Active residues exclude preprocessing trims, junction trims, and optional
        extra exclusions supplied by the caller.
        """

        if extra_exclude is None:
            extra_exclude = set()
        coords: List[np.ndarray] = []
        for res in self.residues.values():
            if res.key in self.pre_trim or res.key in self.trim or res.key in extra_exclude:
                continue
            c1 = res.xyz("C1'")
            if c1 is not None:
                coords.append(c1)
        if len(coords) < 3:
            raise ValueError(f"{self.name}: cannot estimate axis (found {len(coords)} C1' atoms)")
        X = np.stack(coords, axis=0)
        point = X.mean(axis=0)
        Xc = X - point
        _, _, vt = np.linalg.svd(Xc, full_matrices=False)
        axis = vt[0]
        axis = axis / np.linalg.norm(axis)
        return point, axis

    def axis_vector(self) -> np.ndarray:
        """Estimate helical axis direction using PCA on active C1' atoms."""

        return self.axis_line()[1]




