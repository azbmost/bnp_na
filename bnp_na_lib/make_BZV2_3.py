#!/usr/bin/env python3
"""make_BZV2_3.py

Bundled with bnp_na V13.6 from the standalone make_BZV2_3.py script.

Build a multi-segment B-DNA / Z-DNA construct connected by one or more BZ-junction cores.

You provide an alternating list of DNA helix PDBs:
    B1.pdb Z1.pdb B2.pdb Z2.pdb ...

The script inserts a copy of the template BZ-junction (core_BZ.py) between every adjacent
pair of helices, aligns it using sugar atoms (C1',C2',C3',C4',O5',C5'), trims overlapping
base pairs at helix ends (keeps the full core), and finally “ligates” the construct by
outputting *two* continuous DNA strands in a single PDB.

Key behaviour:
  * The input files are assumed to alternate B/Z by order, starting with B.
  * One fresh core_BZ copy is inserted between every adjacent helix pair.
  * B-side fits use 2 bp; Z-side fits use the outermost 1 bp from core_BZ aligned to
    the second bp from the chosen Z-helix end.
  * Axis handling has distinct modes:
      - codirectional (default): rotate the moving helix so its axis direction matches
        the fixed helix axis, but do not apply a lateral axis-line translation. This
        keeps the local junction geometry closer to the sugar-atom fit.
      - collinear: rotate as above, then translate the moving helix laterally so the
        fitted axis lines lie on the same spatial line. This is stricter but can
        stretch junction contacts, so it is no longer the default.
      - none: use only the local junction fit.
    No deliberate rotation about the helical axis is applied by either axis mode.
  * Axis lines for the post-fit axis correction can be estimated using DSSR via
    the imported align2z.py module (default: auto = try DSSR first, fall back to PCA).
  * The final ligated output is numbered 5' -> 3' for both strands.
  * A raw aligned PDB is also written with _raw before the extension. It is aligned
    but not junction-trimmed or ligated.

Z-DNA input requirement and automatic correction:
  * Each input Z-DNA model should be an alternating pyrimidine/purine Z-DNA duplex.
  * For make_BZ, each selected main chain should start with a pyrimidine (C/T/U)
    and end with a purine (A/G) in residue-number order. This puts the terminal
    dinucleotide phase in register with the Z end of core_BZ.
  * If a Z model does not meet this requirement, make_BZV2_3.py tries to pre-trim
    at most 1 base pair from each sequence end to satisfy it. A WARNING is printed
    whenever this automatic Z pre-trimming is applied. For Z-DNA generated by
    DSSR or bnp_na in this workflow, prepare the original Z-DNA input 2 bp
    longer than the target final Z segment so this
    terminal correction can remove 1 bp from each end when needed.
  * If no allowed terminal trim can satisfy the requirement, the script stops with
    an explicit error.

GUI mode:
  * If run with no arguments, or with --gui, a Tkinter GUI is opened so you can choose
    input files and parameters interactively.

Notes / assumptions:
  * Each input helix should be double-stranded DNA with two main chains.
  * ANISOU lines are ignored automatically because edit_pdb_atom.file2rec only parses
    ATOM/HETATM/TER records.
  * “Ligation” here means generating continuous chains (no TER breaks) and consistent
    residue numbering; PDB does not store explicit covalent bonds.

Example CLI:
    python make_BZV2_3.py --out multi_BZ.pdb B1.pdb Z1.pdb

    # Optional strict same-line correction:
    python make_BZV2_3.py --axis-mode collinear --out multi_BZ.pdb B1.pdb Z1.pdb

Dependencies:
  * numpy
  * tkinter (optional; only for GUI mode)
  * edit_pdb_atom.py (provided by you)
  * core_BZ.py (template core module generated from your trimmed 5zup structure)
  * align2z.py (imported, not modified; used for DSSR --more axis extraction when available)
"""

