def load_pdb_records(path: Path) -> List[object]:
    recs: List[object] = []
    with path.open('r') as f:
        file2rec(f, recs)
    return recs


def build_residues(records: List[object], seg_id: str) -> Dict[ResidKey, Residue]:
    # Group ATOM/HETATM by (chainID,resSeq)
    tmp: Dict[Tuple[str, int], List[pdb_atom_record]] = {}
    resname_by: Dict[Tuple[str, int], str] = {}
    for rec in records:
        if not _is_atom_record(rec):
            continue
        key2 = (rec.chainID, rec.resSeq)
        tmp.setdefault(key2, []).append(rec)
        resname_by[key2] = rec.resName

    residues: Dict[ResidKey, Residue] = {}
    for (chainID, resSeq), atomrecs in tmp.items():
        key: ResidKey = (seg_id, chainID, resSeq)
        atom_by_name: Dict[str, pdb_atom_record] = {}
        for a in atomrecs:
            # Keep first occurrence; for altloc situations you might improve this.
            atom_by_name.setdefault(a.name, a)
        residues[key] = Residue(
            key=key,
            chainID=chainID,
            resSeq=resSeq,
            resName=resname_by[(chainID, resSeq)],
            atoms=atomrecs,
            atom_by_name=atom_by_name,
        )
    return residues


def pick_two_main_chains(residues: Dict[ResidKey, Residue]) -> List[str]:
    counts: Dict[str, int] = {}
    for res in residues.values():
        counts[res.chainID] = counts.get(res.chainID, 0) + 1
    if len(counts) < 2:
        raise ValueError(f"Need >=2 chains for dsDNA, found chains={sorted(counts)}")
    # Pick top-2 by residue count, tie-break by chainID
    chains = sorted(counts.keys(), key=lambda c: (-counts[c], c))[:2]
    return chains


def compute_axis_and_projections(
    residues: Dict[ResidKey, Residue],
    chains: List[str],
    exclude: Optional[set] = None,
) -> Tuple[np.ndarray, Dict[ResidKey, float]]:
    if exclude is None:
        exclude = set()
    coords: List[np.ndarray] = []
    keys: List[ResidKey] = []
    for key, res in residues.items():
        if key in exclude:
            continue
        if res.chainID not in chains:
            continue
        c1 = res.xyz("C1'")
        if c1 is None:
            continue
        coords.append(c1)
        keys.append(key)
    if len(coords) < 6:
        raise ValueError(f"Cannot compute axis: only {len(coords)} residues with C1' in main chains {chains}")
    X = np.stack(coords, axis=0)
    mean = X.mean(axis=0)
    Xc = X - mean
    _, _, vt = np.linalg.svd(Xc, full_matrices=False)
    axis = vt[0]
    axis = axis / np.linalg.norm(axis)

    # Choose axis sign so that along the first chain, projections correlate positively with resSeq.
    chain0 = chains[0]
    seqs = []
    ts = []
    for key, res in residues.items():
        if key in exclude:
            continue
        if res.chainID != chain0:
            continue
        c1 = res.xyz("C1'")
        if c1 is None:
            continue
        t = float(np.dot(c1 - mean, axis))
        seqs.append(res.resSeq)
        ts.append(t)
    if len(seqs) >= 3:
        corr = np.corrcoef(seqs, ts)[0, 1]
        if not np.isnan(corr) and corr < 0:
            axis = -axis

    proj: Dict[ResidKey, float] = {}
    for key, res in residues.items():
        if key in exclude:
            continue
        if res.chainID not in chains:
            continue
        c1 = res.xyz("C1'")
        if c1 is None:
            continue
        proj[key] = float(np.dot(c1 - mean, axis))
    return axis, proj


def build_basepairs(
    residues: Dict[ResidKey, Residue],
    chains: List[str],
    exclude: Optional[set] = None,
) -> List[Tuple[ResidKey, ResidKey]]:
    if exclude is None:
        exclude = set()
    axis, proj = compute_axis_and_projections(residues, chains, exclude=exclude)
    # Sort residues in each chain by projection (physical order)
    chain_res: Dict[str, List[ResidKey]] = {chains[0]: [], chains[1]: []}
    for key, res in residues.items():
        if key in exclude:
            continue
        if res.chainID in chain_res and key in proj:
            chain_res[res.chainID].append(key)

    for c in chain_res:
        chain_res[c].sort(key=lambda k: proj[k])

    n = min(len(chain_res[chains[0]]), len(chain_res[chains[1]]))
    if n < 2:
        raise ValueError(f"Not enough residues to form basepairs: chain lengths {[len(chain_res[c]) for c in chains]}")

    bp: List[Tuple[ResidKey, ResidKey]] = []
    for i in range(n):
        bp.append((chain_res[chains[0]][i], chain_res[chains[1]][i]))
    return bp


def load_helix(path: Path, seg_id: str) -> Structure:
    records = load_pdb_records(path)
    residues = build_residues(records, seg_id=seg_id)
    chains = pick_two_main_chains(residues)
    basepairs = build_basepairs(residues, chains)
    return Structure(name=path.name, seg_id=seg_id, records=records, residues=residues, chains=chains, basepairs=basepairs)


