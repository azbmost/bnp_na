_ALIGN2Z_MODULE = None
_ALIGN2Z_IMPORT_ERROR: Optional[BaseException] = None
_DSSR_AUTO_FALLBACK_REPORTED = False


def _install_geometry_utils_stub_for_align2z() -> None:
    """Install a tiny in-memory geometry_utils fallback so align2z.py can import.

    Some distributions of align2z.py live inside a larger package that provides
    geometry_utils.py. We do not modify align2z.py; this only supplies the two names
    it imports if that package module is absent in the current folder.
    """

    if "geometry_utils" in sys.modules:
        return

    mod = types.ModuleType("geometry_utils")

    class GeometryError(Exception):
        pass

    def rotation_matrix_from_to(v_from, v_to):
        try:
            return rotation_matrix_from_vectors(np.asarray(v_from, dtype=float), np.asarray(v_to, dtype=float))
        except Exception as exc:
            raise GeometryError(str(exc)) from exc

    mod.GeometryError = GeometryError
    mod.rotation_matrix_from_to = rotation_matrix_from_to
    sys.modules["geometry_utils"] = mod


def _get_align2z_module():
    """Import align2z.py lazily without modifying that file."""

    global _ALIGN2Z_MODULE, _ALIGN2Z_IMPORT_ERROR
    if _ALIGN2Z_MODULE is not None:
        return _ALIGN2Z_MODULE

    try:
        _ALIGN2Z_MODULE = importlib.import_module("align2z")
        return _ALIGN2Z_MODULE
    except ModuleNotFoundError as exc:
        if exc.name != "geometry_utils":
            _ALIGN2Z_IMPORT_ERROR = exc
            raise
        sys.modules.pop("align2z", None)
        _install_geometry_utils_stub_for_align2z()
        try:
            _ALIGN2Z_MODULE = importlib.import_module("align2z")
            return _ALIGN2Z_MODULE
        except BaseException as exc2:
            _ALIGN2Z_IMPORT_ERROR = exc2
            raise
    except BaseException as exc:
        _ALIGN2Z_IMPORT_ERROR = exc
        raise


def _active_structure_records_for_axis(struct: Structure, extra_exclude: Optional[set] = None) -> List[object]:
    """Return deep-copied ATOM/TER records for active residues used by DSSR.

    ``rec2file(..., reorder_serial=True)`` mutates record serial numbers, so this
    function always deep-copies atom records before writing the temporary PDB.
    """

    if extra_exclude is None:
        extra_exclude = set()
    out_recs: List[object] = []
    for chainID in struct.chains:
        keys = [
            k for k, r in struct.residues.items()
            if r.chainID == chainID and k not in struct.pre_trim and k not in struct.trim and k not in extra_exclude
        ]
        keys.sort(key=lambda k: struct.residues[k].resSeq)
        if not keys:
            continue
        for key in keys:
            out_recs.extend(copy.deepcopy(struct.residues[key].atoms))
        last_res = struct.residues[keys[-1]]
        line = f"TER   {0:5d}      {last_res.resName:>3} {chainID}{last_res.resSeq:4d}\n"
        out_recs.append(pdb_ter_record(line))
    return out_recs


def axis_line_dssr(struct: Structure, extra_exclude: Optional[set] = None) -> AxisLineResult:
    """Estimate a helix axis line using DSSR --more through imported align2z.py."""

    align2z_mod = _get_align2z_module()
    with tempfile.TemporaryDirectory(prefix="make_BZ_axis_") as tmpdir:
        tmp = Path(tmpdir)
        safe_name = struct.name.replace('/', '_').replace(' ', '_')
        pdb_path = tmp / f"{struct.seg_id}_{safe_name}_axis.pdb"
        out_txt = tmp / f"{struct.seg_id}_dssr_more.out"
        recs = _active_structure_records_for_axis(struct, extra_exclude=extra_exclude)
        if not recs:
            raise RuntimeError(f"{struct.name}: no active records available for DSSR axis fitting")
        with pdb_path.open("w", encoding="utf-8") as fout:
            rec2file(recs, fout, reorder_serial=True)
            fout.write("END\n")

        ok, dssr_log, cmd = align2z_mod.run_dssr_more_axis(pdb_path, out_txt, cwd=tmp)
        cmd_text = align2z_mod.command_to_text(cmd) if cmd else "x3dna-dssr command unavailable"
        if not ok or not out_txt.exists():
            raise RuntimeError(
                "DSSR --more axis extraction failed. "
                f"Command: {cmd_text}. Output: {dssr_log or '(no output)'}"
            )
        p1, p2 = align2z_mod.parse_first_axis_points(out_txt)
        p1_arr = np.asarray(p1, dtype=float)
        p2_arr = np.asarray(p2, dtype=float)
        v = p2_arr - p1_arr
        n = float(np.linalg.norm(v))
        if n < 1e-8:
            raise RuntimeError("DSSR point-one and point-two define a near-zero axis length")
        return AxisLineResult(
            point=p1_arr,
            direction=v / n,
            source="DSSR/align2z",
            detail=f"command={cmd_text}; point-one={p1_arr.tolist()}; point-two={p2_arr.tolist()}",
        )


def axis_line_pca(struct: Structure, extra_exclude: Optional[set] = None) -> AxisLineResult:
    point, direction = struct.axis_line(extra_exclude=extra_exclude)
    return AxisLineResult(point=point, direction=direction, source="PCA(C1')", detail="fallback/local PCA")


def get_axis_line(
    struct: Structure,
    *,
    source: str,
    extra_exclude: Optional[set] = None,
    verbose_prefix: str = "",
    label: str = "helix",
) -> AxisLineResult:
    """Return an axis line using DSSR/align2z, PCA, or auto fallback."""

    global _DSSR_AUTO_FALLBACK_REPORTED
    src = (source or "auto").strip().lower()
    if src not in ("auto", "dssr", "pca"):
        raise ValueError(f"Unknown axis source: {source}")

    if src in ("auto", "dssr"):
        try:
            result = axis_line_dssr(struct, extra_exclude=extra_exclude)
            print(f"{verbose_prefix} axis[{label}] source={result.source}; {result.detail}")
            return result
        except BaseException as exc:
            if src == "dssr":
                raise RuntimeError(f"DSSR axis source requested but failed for {struct.name}: {exc}") from exc
            if not _DSSR_AUTO_FALLBACK_REPORTED:
                print(
                    f"{verbose_prefix} WARNING: DSSR/align2z axis extraction failed in auto mode; "
                    f"falling back to PCA(C1') for this run. Reason: {exc}"
                )
                _DSSR_AUTO_FALLBACK_REPORTED = True

    result = axis_line_pca(struct, extra_exclude=extra_exclude)
    print(f"{verbose_prefix} axis[{label}] source={result.source}; {result.detail}")
    return result


