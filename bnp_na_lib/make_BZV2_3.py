PURINES = {'A', 'G'}
PYRIMIDINES = {'C', 'T', 'U'}


def _base_code(resName: str) -> Optional[str]:
    """Return A/C/G/T/U for common DNA/RNA residue names (DA/DC/... or A/C/...)."""

    s = (resName or '').strip().upper()
    for ch in reversed(s):
        if ch in {'A', 'C', 'G', 'T', 'U'}:
            return ch
    return None


def _chain_residues_by_resseq(struct: Structure, chainID: str, exclude: Optional[set] = None) -> List[Residue]:
    """Return residues in one chain sorted by residue number, excluding requested keys."""

    if exclude is None:
        exclude = set()
    residues = [r for r in struct.residues.values() if r.chainID == chainID and r.key not in exclude]
    residues.sort(key=lambda r: r.resSeq)
    return residues


def _z_requirement_status(struct: Structure, exclude: Optional[set] = None) -> Tuple[bool, List[str]]:
    """Check the make_BZ Z-DNA sequence-phase requirement.

    Requirement: every selected main chain should start with a pyrimidine and end with
    a purine in residue-number order. This is the Z-DNA terminal phase expected by the
    Z end of core_BZ.
    """

    if exclude is None:
        exclude = set()
    messages: List[str] = []
    ok_all = True
    for chainID in struct.chains:
        residues = _chain_residues_by_resseq(struct, chainID, exclude=exclude)
        if len(residues) < 3:
            ok_all = False
            messages.append(f"chain {chainID}: too few residues after trimming ({len(residues)})")
            continue
        first = _base_code(residues[0].resName)
        last = _base_code(residues[-1].resName)
        ok = first in PYRIMIDINES and last in PURINES
        ok_all = ok_all and ok
        messages.append(
            f"chain {chainID}: start={residues[0].resName}{residues[0].resSeq}({first}), "
            f"end={residues[-1].resName}{residues[-1].resSeq}({last}), ok={'Y' if ok else 'N'}"
        )
    return ok_all, messages


def _candidate_terminal_trim_keys(struct: Structure, start_bp_trim: int, end_bp_trim: int) -> set:
    """Return residue keys removed by trimming terminal bp from both chains by resSeq order."""

    trim_keys = set()
    for chainID in struct.chains:
        residues = _chain_residues_by_resseq(struct, chainID)
        if start_bp_trim + end_bp_trim >= len(residues) - 2:
            # Leave at least three residues per chain for a meaningful helix end/anchor.
            return set(struct.residues.keys())
        trim_keys.update(r.key for r in residues[:start_bp_trim])
        if end_bp_trim:
            trim_keys.update(r.key for r in residues[-end_bp_trim:])
    return trim_keys


def apply_z_auto_trim_if_needed(struct: Structure, filename: str) -> None:
    """Pre-trim terminal Z-DNA bp when needed to satisfy the required terminal phase.

    If the untrimmed Z model already satisfies the requirement, no changes are made.
    Otherwise the function tries four possibilities: no extra trim, 1 bp from the
    sequence start, 1 bp from the sequence end, or 1 bp from both ends. It chooses
    the solution with the fewest total removed base pairs. The selected residues are
    stored in ``struct.pre_trim`` and the structure's basepair list is rebuilt using
    only the remaining residues.
    """

    ok, messages = _z_requirement_status(struct, exclude=struct.pre_trim)
    if ok:
        print(f"  Z-check OK for {filename}: each main chain starts with pyrimidine and ends with purine.")
        for msg in messages:
            print(f"    {msg}")
        return

    print(f"  WARNING: Z-check failed for {filename}; trying terminal Z-DNA pre-trimming.")
    for msg in messages:
        print(f"    before: {msg}")

    best = None
    for total in range(0, 3):
        for start_trim in range(0, 2):
            for end_trim in range(0, 2):
                if start_trim + end_trim != total:
                    continue
                candidate = _candidate_terminal_trim_keys(struct, start_trim, end_trim)
                ok_candidate, candidate_messages = _z_requirement_status(struct, exclude=candidate)
                if ok_candidate:
                    best = (start_trim, end_trim, candidate, candidate_messages)
                    break
            if best is not None:
                break
        if best is not None:
            break

    if best is None:
        raise SystemExit(
            f"ERROR: Z-DNA file {filename} does not satisfy the required terminal phase, and no "
            f"auto-trim solution was found when allowing at most 1 bp removal from each Z-DNA end. "
            "Expected each main chain to start with pyrimidine (C/T/U) and end with purine (A/G)."
        )

    start_trim, end_trim, trim_keys, after_messages = best
    struct.pre_trim.update(trim_keys)
    struct.basepairs = build_basepairs(struct.residues, struct.chains, exclude=struct.pre_trim)

    print(
        f"  WARNING: Z-DNA file {filename} was pre-trimmed to satisfy terminal phase: "
        f"start_bp_trim={start_trim}, end_bp_trim={end_trim}, residues_removed={len(trim_keys)}."
    )
    print("  The raw aligned PDB and final ligated PDB will exclude these pre-trimmed terminal residues.")
    for msg in after_messages:
        print(f"    after:  {msg}")
    print(f"  Z-check OK after pre-trimming; active basepairs={len(struct.basepairs)}")


def _bp_centroid(struct: Structure, bp: Tuple[ResidKey, ResidKey], atom: str = "C1'") -> np.ndarray:
    pts: List[np.ndarray] = []
    for rk in bp:
        xyz = struct.residues[rk].xyz(atom)
        if xyz is None:
            raise ValueError(f"{struct.name}: missing {atom} on residue {rk[1]}{rk[2]}")
        pts.append(xyz)
    return np.mean(np.stack(pts, axis=0), axis=0)


def end_outward_vector(struct: Structure, end: str) -> np.ndarray:
    """Unit vector pointing from the helix interior towards the requested physical end."""

    bps = struct.end_basepairs(end, n_bp=2)  # interior -> outer
    inner = _bp_centroid(struct, bps[0])
    outer = _bp_centroid(struct, bps[1])
    v = outer - inner
    n = np.linalg.norm(v)
    if n < 1e-8:
        raise ValueError(f"{struct.name}: cannot define outward vector at {end} (degenerate)")
    return v / n


def core_through_vector(core: Structure, core_end_fixed: str, core_end_next: str) -> np.ndarray:
    """Unit vector from the core's fixed-side outer bp to its next-side outer bp."""

    bp_fixed = _core_outer_basepair(core, core_end_fixed)
    bp_next = _core_outer_basepair(core, core_end_next)
    p_fixed = _bp_centroid(core, bp_fixed)
    p_next = _bp_centroid(core, bp_next)
    v = p_next - p_fixed
    n = np.linalg.norm(v)
    if n < 1e-8:
        raise ValueError(f"{core.name}: cannot define through-vector (degenerate)")
    return v / n


