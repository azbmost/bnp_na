def _coords_for_basepairs(struct: Structure, bps: List[Tuple[ResidKey, ResidKey]], swap_strands: bool) -> np.ndarray:
    pts: List[np.ndarray] = []
    for (r1, r2) in bps:
        if swap_strands:
            r1, r2 = r2, r1
        for rk in (r1, r2):
            res = struct.residues[rk]
            for at in SUGAR_ATOMS:
                xyz = res.xyz(at)
                if xyz is None:
                    raise ValueError(f"{struct.name}: residue {res.chainID}{res.resSeq} missing atom {at} (or alias)")
                pts.append(xyz)
    return np.stack(pts, axis=0)


def align_moving_to_fixed(
    *,
    fixed: Structure,
    fixed_end: str,
    moving: Structure,
    moving_end_kind: str,
    core_end: str,
    verbose_prefix: str,
) -> Tuple[float, bool]:
    """Align a moving *core* end onto a fixed helix end.

    Alignment atoms are the sugar atoms listed in ``SUGAR_ATOMS``.

    Rules:
      * If ``core_end == 'B'``: fit using 2 bp (core B-end 2 bp <-> helix end 2 bp).
      * If ``core_end == 'Z'`` (v1.1 behaviour): fit using **only the outermost 1 bp**
        from the core's Z-end, aligned to the **second bp** from the helix end.

    Returns
    -------
    (rmsd, swap_strands)
      swap_strands refers to whether we had to swap the *fixed* helix strand mapping
      to get the lowest RMSD.
    """

    if moving_end_kind != 'core':
        raise ValueError("align_moving_to_fixed only supports moving_end_kind='core' here")

    # Decide which basepairs to use for alignment.
    if core_end == 'B':
        # For B-end: use helix end basepairs in outer->inner order so that after trimming 2 bp,
        # the helix *anchor* bp (3rd from end) sits adjacent to the core *outer* bp.
        fixed_bps = list(reversed(fixed.end_basepairs(fixed_end, n_bp=2)))
        bps_raw = list(core_BZ.B_END_BASEPAIRS)  # interior -> outer
        note = '2bp (helix order outer->inner)'
    elif core_end == 'Z':
        # Use the *second* bp from the helix end (index 0 in our interior->outer list)
        fixed_bps2 = fixed.end_basepairs(fixed_end, n_bp=2)
        fixed_bps = [fixed_bps2[0]]

        # Use only the *outermost* bp from the core Z-end (last in interior->outer list)
        bps_raw_all = list(core_BZ.Z_END_BASEPAIRS)
        bps_raw = [bps_raw_all[-1]]
        note = '1bp(core outer) -> helix second bp'
    else:
        raise ValueError(f"core_end must be 'B' or 'Z', got {core_end}")

    # Convert (chain,resSeq) -> ResidKey
    moving_bps: List[Tuple[ResidKey, ResidKey]] = []
    for (a, b) in bps_raw:
        ka: ResidKey = (moving.seg_id, a[0], int(a[1]))
        kb: ResidKey = (moving.seg_id, b[0], int(b[1]))
        moving_bps.append((ka, kb))

    best = None
    for swap in (False, True):
        P = _coords_for_basepairs(moving, moving_bps, swap_strands=False)  # core: keep as-is
        Q = _coords_for_basepairs(fixed, fixed_bps, swap_strands=swap)
        R, t, rmsd = kabsch(P, Q)
        if best is None or rmsd < best[0]:
            best = (rmsd, swap, R, t)

    assert best is not None
    rmsd, swap, R, t = best

    apply_rigid_transform(moving.records, R, t)

    print(
        f"{verbose_prefix} align core({core_end}-end) -> fixed[{fixed.name}] {fixed_end}-end: "
        f"rmsd={rmsd:.3f} A, strand_swap={'Y' if swap else 'N'}  [{note}]"
    )
    return rmsd, swap


def align_helix_to_core(
    *,
    helix: Structure,
    preferred_end: str,
    core: Structure,
    core_end: str,
    junction_dir: np.ndarray,
    verbose_prefix: str,
    auto_switch_if_better: bool = True,
) -> Tuple[str, float, bool, np.ndarray, float]:
    """Move a helix onto a positioned core end.

    We test both strand-mapping options (swap / no swap). Optionally we also test
    the opposite helix end. A candidate is preferred only if the far end of the
    helix extends forward along ``junction_dir`` (fixed helix -> core -> next helix),
    which prevents fold-back overlap.

    Rules:
      * If ``core_end == 'B'``: fit using 2 bp (helix end 2 bp <-> core B-end 2 bp).
      * If ``core_end == 'Z'``: fit using only the outermost 1 bp from the core Z-end,
        aligned to the second bp from the chosen helix end.

    Returns:
      chosen_end, rmsd, strand_swap, pivot_xyz, direction_cosine
    """

    if core_end == 'B':
        bps_raw = list(core_BZ.B_END_BASEPAIRS)  # interior -> outer
        note = '2bp'
    elif core_end == 'Z':
        bps_raw_all = list(core_BZ.Z_END_BASEPAIRS)
        bps_raw = [bps_raw_all[-1]]  # outermost Z-end bp in core_BZ
        note = '1bp(core outer) -> helix second bp'
    else:
        raise ValueError(f"core_end must be 'B' or 'Z', got {core_end}")

    core_bps: List[Tuple[ResidKey, ResidKey]] = []
    for (a, b) in bps_raw:
        ka: ResidKey = (core.seg_id, a[0], int(a[1]))
        kb: ResidKey = (core.seg_id, b[0], int(b[1]))
        core_bps.append((ka, kb))

    candidate_ends = [preferred_end]
    other_end = 'start' if preferred_end == 'end' else 'end'
    if auto_switch_if_better:
        candidate_ends.append(other_end)

    Qcore = _coords_for_basepairs(core, core_bps, swap_strands=False)
    pivot = Qcore.mean(axis=0)

    best_good = None
    best_any = None

    for helix_end in candidate_ends:
        if core_end == 'B':
            helix_bps = list(reversed(helix.end_basepairs(helix_end, n_bp=2)))
        else:
            helix_bps2 = helix.end_basepairs(helix_end, n_bp=2)
            helix_bps = [helix_bps2[0]]  # second bp from this Z helix end

        if helix_end == 'start':
            bp_connect = helix.basepairs[0]
            bp_far = helix.basepairs[-1]
        else:
            bp_connect = helix.basepairs[-1]
            bp_far = helix.basepairs[0]
        p_connect0 = _bp_centroid(helix, bp_connect)
        p_far0 = _bp_centroid(helix, bp_far)

        for swap in (False, True):
            P = _coords_for_basepairs(helix, helix_bps, swap_strands=swap)
            R, t, rmsd = kabsch(P, Qcore)

            p_connect = R @ p_connect0 + t
            p_far = R @ p_far0 + t
            ext = p_far - p_connect
            ext_len = float(np.linalg.norm(ext))
            proj = float(np.dot(ext, junction_dir))
            dot_unit = proj / ext_len if ext_len > 1e-12 else -1.0

            cand = (rmsd, helix_end, swap, R, t, dot_unit, proj)
            if best_any is None or rmsd < best_any[0]:
                best_any = cand
            if dot_unit > 0:
                if best_good is None or rmsd < best_good[0]:
                    best_good = cand

    assert best_any is not None
    chosen = best_good if best_good is not None else best_any
    rmsd, chosen_end, swap, R, t, dot_unit, proj = chosen

    apply_rigid_transform(helix.records, R, t)

    switched = (chosen_end != preferred_end)
    msg = (
        f"{verbose_prefix} align helix[{helix.name}] {chosen_end}-end -> core({core_end}-end): "
        f"rmsd={rmsd:.3f} A, strand_swap={'Y' if swap else 'N'}  [{note}]  "
        f"dir_cos={dot_unit:.3f} (proj={proj:.1f} A)"
    )
    if switched:
        msg += f"  (NOTE: preferred_end={preferred_end} but chose {chosen_end})"
    if best_good is None:
        msg += "  WARNING: no candidate satisfied forward-direction; using lowest RMSD anyway"
    print(msg)

    return chosen_end, rmsd, swap, pivot, dot_unit

def normalize_axis_mode(mode: Optional[str]) -> str:
    """Normalize user-facing axis-mode text."""

    m = (mode or 'codirectional').strip().lower()
    if m in ('collinear',):
        return 'collinear'
    if m in ('codirectional', 'co-directional', 'co_directional', 'direction', 'y', 'yes', 'true'):
        return 'codirectional'
    if m in ('none', 'n', 'no', 'false'):
        return 'none'
    raise ValueError(f"Unknown axis mode: {mode}")


def enforce_axis_alignment(
    *,
    fixed_helix: Structure,
    moving_helix: Structure,
    pivot: np.ndarray,
    junction_dir: np.ndarray,
    verbose_prefix: str,
    mode: str = 'codirectional',
    axis_source: str = 'auto',
    fixed_extra_exclude: Optional[set] = None,
    moving_extra_exclude: Optional[set] = None,
) -> None:
    """Enforce co-directional or true-collinear helix axes.

    ``mode='codirectional'`` reproduces the older behavior: it applies the minimal
    rotation that makes the moving helix axis direction parallel/co-directional with
    the fixed helix axis direction. This is an axis-tilt correction and does not
    intentionally rotate about the helical axis.

    ``mode='collinear'`` first performs the same direction correction, then translates
    the moving helix by the perpendicular offset needed to put the two fitted axis
    lines on the same infinite spatial line. The translation has no rotational
    component, so it also does not add twist.

    Axis lines are obtained by ``axis_source``: ``auto`` tries DSSR via imported
    align2z.py and falls back to PCA, ``dssr`` requires DSSR, and ``pca`` uses the
    original C1' PCA estimate.
    """

    normalized_mode = normalize_axis_mode(mode)
    if normalized_mode == 'none':
        print(f"{verbose_prefix} axis-mode=none: no post-fit axis correction applied.")
        return

    if fixed_extra_exclude is None:
        fixed_extra_exclude = set()
    if moving_extra_exclude is None:
        moving_extra_exclude = set()

    fixed_axis = get_axis_line(fixed_helix, source=axis_source, extra_exclude=fixed_extra_exclude, verbose_prefix=verbose_prefix, label='fixed')
    moving_axis = get_axis_line(moving_helix, source=axis_source, extra_exclude=moving_extra_exclude, verbose_prefix=verbose_prefix, label='moving-before')
    pf, u = fixed_axis.point, fixed_axis.direction
    pm, v = moving_axis.point, moving_axis.direction

    if np.dot(u, junction_dir) < 0:
        u = -u
    if np.dot(v, junction_dir) < 0:
        v = -v

    dot = float(np.dot(u, v))
    dot = max(-1.0, min(1.0, dot))
    angle_before = math.degrees(math.acos(dot))
    offset_before = axis_line_distance(pf, u, pm, v)

    if angle_before >= 1e-3:
        R = rotation_matrix_from_vectors(v, u)
        apply_rotation_about_point(moving_helix.records, R, pivot)

    moving_axis2 = get_axis_line(moving_helix, source=axis_source, extra_exclude=moving_extra_exclude, verbose_prefix=verbose_prefix, label='moving-after-rotation')
    pm2, v2 = moving_axis2.point, moving_axis2.direction
    if np.dot(v2, junction_dir) < 0:
        v2 = -v2
    dot2 = float(np.dot(u, v2))
    dot2 = max(-1.0, min(1.0, dot2))
    angle_after_rotation = math.degrees(math.acos(dot2))
    offset_after_rotation = axis_line_distance(pf, u, pm2, v2)

    if normalized_mode == 'codirectional':
        print(
            f"{verbose_prefix} codirectional: axis angle {angle_before:.3f} -> {angle_after_rotation:.3f} deg; "
            f"axis-line offset {offset_before:.3f} -> {offset_after_rotation:.3f} A (no axis-line shift)."
        )
        return

    shift = perpendicular_shift_to_collinear(pf, u, pm2)
    shift_mag = float(np.linalg.norm(shift))
    if shift_mag > 1e-8:
        apply_translation(moving_helix.records, shift)

    moving_axis3 = get_axis_line(moving_helix, source=axis_source, extra_exclude=moving_extra_exclude, verbose_prefix=verbose_prefix, label='moving-after-shift')
    pm3, v3 = moving_axis3.point, moving_axis3.direction
    if np.dot(v3, junction_dir) < 0:
        v3 = -v3
    dot3 = float(np.dot(u, v3))
    dot3 = max(-1.0, min(1.0, dot3))
    angle_after = math.degrees(math.acos(dot3))
    offset_after = axis_line_distance(pf, u, pm3, v3)

    print(
        f"{verbose_prefix} collinear: axis direction angle {angle_before:.3f} -> {angle_after_rotation:.3f} -> {angle_after:.3f} deg; "
        f"axis-line offset {offset_before:.3f} -> {offset_after_rotation:.3f} -> {offset_after:.3f} A; "
        f"perpendicular shift={shift_mag:.3f} A."
    )
    if shift_mag > 0.5:
        print(
            f"{verbose_prefix} WARNING: strict collinear mode shifted the moving helix by {shift_mag:.3f} A. "
            "This enforces a common axis line but may slightly worsen local junction contact geometry. "
            "Use the default --axis-mode codirectional for no-shift behavior."
        )


def enforce_collinear_axes(
    *,
    fixed_helix: Structure,
    moving_helix: Structure,
    pivot: np.ndarray,
    junction_dir: np.ndarray,
    verbose_prefix: str,
) -> None:
    """Backward-compatible wrapper: optional strict true-collinear mode."""

    enforce_axis_alignment(
        fixed_helix=fixed_helix,
        moving_helix=moving_helix,
        pivot=pivot,
        junction_dir=junction_dir,
        verbose_prefix=verbose_prefix,
        mode='collinear',
        axis_source='auto',
    )


