def parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    return build_arg_parser().parse_args(argv)


def effective_axis_mode(args: argparse.Namespace) -> str:
    """Resolve --axis-mode plus legacy --collinear into one internal mode."""

    if getattr(args, 'axis_mode', None) is not None:
        if getattr(args, 'collinear', None) is not None:
            print(f"NOTE: --axis-mode {args.axis_mode} overrides legacy --collinear {args.collinear}.")
        return normalize_axis_mode(args.axis_mode)
    if getattr(args, 'collinear', None) is not None:
        return normalize_axis_mode(args.collinear)
    return 'codirectional'


def effective_axis_source(args: argparse.Namespace) -> str:
    """Resolve and validate --axis-source."""

    source = getattr(args, 'axis_source', 'auto')
    src = (source or 'auto').strip().lower()
    if src not in ('auto', 'dssr', 'pca'):
        raise ValueError(f"Unknown axis source: {source}")
    return src

def resolve_output_path(out_text: str, input_paths: Sequence[Path]) -> Path:
    """Resolve output path; parser default goes to the first input file's folder."""

    out_path = Path(out_text)
    if out_text == DEFAULT_OUTPUT_NAME and not out_path.is_absolute() and input_paths:
        first_parent = input_paths[0].expanduser().resolve().parent
        return first_parent / DEFAULT_OUTPUT_NAME
    return out_path


def raw_output_path(out_path: Path) -> Path:
    if out_path.suffix:
        return out_path.with_name(out_path.stem + '_raw' + out_path.suffix)
    return out_path.with_name(out_path.name + '_raw.pdb')


def run_pipeline(args: argparse.Namespace) -> None:
    axis_mode = effective_axis_mode(args)
    paths = [Path(p) for p in args.dna_files]
    for p in paths:
        if not p.exists():
            raise SystemExit(f"ERROR: input file not found: {p}")

    n_files = len(paths)
    if n_files < 2:
        raise SystemExit("ERROR: need at least 2 files (B1 Z1)")

    # Assign types by position: B, Z, B, Z, ...
    types = ['B' if i % 2 == 0 else 'Z' for i in range(n_files)]
    nB = sum(1 for t in types if t == 'B')
    nZ = sum(1 for t in types if t == 'Z')
    if nB < 1 or nZ < 1:
        raise SystemExit("ERROR: need >=1 B model and >=1 Z model")
    if nB < nZ:
        raise SystemExit(f"ERROR: number of B models must be >= number of Z models (got B={nB}, Z={nZ})")


    print("Input files (assumed alternating B/Z by order):")
    for i, (t, p) in enumerate(zip(types, paths), start=1):
        print(f"  {i:2d}. {t}  {p}")
    print(f"Junctions to build: {n_files - 1} -> cores to insert: {n_files - 1}")
    print(f"Axis correction mode: {axis_mode}")
    axis_source = effective_axis_source(args)
    print(f"Axis source: {axis_source}")
    if axis_source == 'auto':
        print("  auto = try DSSR axis via imported align2z.py; fall back to PCA if unavailable.")
    elif axis_source == 'dssr':
        print("  dssr = require DSSR axis via imported align2z.py; stop if unavailable.")
    else:
        print("  pca = use internal C1' PCA axis estimate only.")
    if axis_mode == 'collinear':
        print("  collinear = rotate axes parallel, then translate moving helix so the fitted axis lines coincide (optional strict mode).")
    elif axis_mode == 'codirectional':
        print("  codirectional = rotate axes parallel only; no lateral axis-line shift (default).")
    else:
        print("  none = no post-fit axis correction.")
    print(
        "Z-DNA requirement: every selected Z chain should start with pyrimidine (C/T/U) "
        "and end with purine (A/G)."
    )

    # Load helices and preprocess Z-DNA terminal phase if needed.
    helices: List[Structure] = []
    for idx, (p, t) in enumerate(zip(paths, types)):
        seg_id = f"seg{idx+1}"
        st = load_helix(p, seg_id=seg_id)
        if t == 'Z':
            if args.no_z_auto_trim:
                ok, messages = _z_requirement_status(st)
                if not ok:
                    for msg in messages:
                        print(f"  Z-check failed for {p.name}: {msg}")
                    raise SystemExit(
                        f"ERROR: Z-DNA file {p.name} does not satisfy the required terminal phase and --no-z-auto-trim was used."
                    )
                print(f"  Z-check OK for {p.name}: each main chain starts with pyrimidine and ends with purine.")
                for msg in messages:
                    print(f"    {msg}")
            else:
                apply_z_auto_trim_if_needed(st, p.name)
        helices.append(st)
        chain_counts = {
            c: sum(1 for r in st.residues.values() if r.chainID == c and r.key not in st.pre_trim)
            for c in st.chains
        }
        print(f"Loaded {p.name}: chains={st.chains} active_residue_counts={chain_counts} basepairs={len(st.basepairs)}")

    # First helix: treat its 'start' as backward terminus, so we connect forward from 'end' by default.
    helices[0].backward_end = 'start'

    all_structs: List[Structure] = [helices[0]]
    junctions: List[JunctionInfo] = []

    # Build junctions sequentially.
    for j in range(n_files - 1):
        fixed = helices[j]
        moving_helix = helices[j + 1]

        junction_id = j + 1
        prefix = f"[J{junction_id}]"

        t_fixed = types[j]
        t_next = types[j + 1]

        if (t_fixed, t_next) == ('B', 'Z'):
            core_end_fixed = 'B'
            core_end_next = 'Z'
        elif (t_fixed, t_next) == ('Z', 'B'):
            core_end_fixed = 'Z'
            core_end_next = 'B'
        else:
            raise SystemExit(f"ERROR: input files must strictly alternate B/Z; got {t_fixed}->{t_next} at junction {junction_id}")

        fixed_end = fixed.forward_end()

        # Create and align a fresh core to the fixed helix. For the first junction, try both
        # ends of the first helix, and prefer core placements that point outward from that end.
        if j == 0:
            other_end = 'start' if fixed_end == 'end' else 'end'
            best_good = None
            best_any = None
            for try_end in (fixed_end, other_end):
                core_try = new_core(seg_id=f"core{junction_id}")
                rmsd_try, swap_try = align_moving_to_fixed(
                    fixed=fixed,
                    fixed_end=try_end,
                    moving=core_try,
                    moving_end_kind='core',
                    core_end=core_end_fixed,
                    verbose_prefix=prefix + ' [try]',
                )

                fixed_out = end_outward_vector(fixed, try_end)
                core_dir = core_through_vector(core_try, core_end_fixed, core_end_next)
                dot_dir = float(np.dot(core_dir, fixed_out))
                print(f"{prefix} [try] direction check: dot(core_dir, fixed_out)={dot_dir:.3f} (try_end={try_end})")

                cand = (rmsd_try, try_end, core_try, swap_try, dot_dir)
                if best_any is None or rmsd_try < best_any[0]:
                    best_any = cand
                if dot_dir > 0:
                    if best_good is None or rmsd_try < best_good[0]:
                        best_good = cand

            assert best_any is not None
            chosen = best_good if best_good is not None else best_any
            _rmsd_best, fixed_end, core, swap_fixed, dot_dir = chosen
            if best_good is None:
                print(f"{prefix} WARNING: could not find an outward-pointing core placement; using lowest RMSD")
            fixed.backward_end = 'start' if fixed_end == 'end' else 'end'
            print(f"{prefix} selected fixed_end={fixed_end} for first junction (backward_end={fixed.backward_end})")
        else:
            core = new_core(seg_id=f"core{junction_id}")
            _rmsd1, swap_fixed = align_moving_to_fixed(
                fixed=fixed,
                fixed_end=fixed_end,
                moving=core,
                moving_end_kind='core',
                core_end=core_end_fixed,
                verbose_prefix=prefix,
            )
            fixed_out = end_outward_vector(fixed, fixed_end)
            core_dir = core_through_vector(core, core_end_fixed, core_end_next)
            dot_dir = float(np.dot(core_dir, fixed_out))
            if dot_dir <= 0:
                print(
                    f"{prefix} WARNING: core through-vector is not pointing outward from fixed helix end "
                    f"(dot={dot_dir:.3f}). This may indicate an orientation problem."
                )

        if j == 0:
            print(f"{prefix} using core aligned to fixed_end={fixed_end} (auto-selected)")

        junction_dir = core_through_vector(core, core_end_fixed, core_end_next)

        # Align next helix to the other end of the core.
        preferred_next_end = 'start'
        chosen_end, rmsd2, swap_next, pivot, dot_ext = align_helix_to_core(
            helix=moving_helix,
            preferred_end=preferred_next_end,
            core=core,
            core_end=core_end_next,
            junction_dir=junction_dir,
            verbose_prefix=prefix,
            auto_switch_if_better=True,
        )
        moving_helix.backward_end = chosen_end

        if dot_ext <= 0:
            print(
                f"{prefix} WARNING: next helix extension is not forward along junction_dir (dir_cos={dot_ext:.3f}). "
                "The model may overlap/fold-back."
            )

        if axis_mode != 'none':
            enforce_axis_alignment(
                fixed_helix=fixed,
                moving_helix=moving_helix,
                pivot=pivot,
                junction_dir=junction_dir,
                verbose_prefix=prefix,
                mode=axis_mode,
                axis_source=axis_source,
            )

        # Mark overlapping basepairs for deletion:
        #   fixed: delete its forward end 2 bp
        #   moving helix: delete its backward end 2 bp
        fixed_bps_to_trim = fixed.end_basepairs(fixed_end, n_bp=2)
        moving_bps_to_trim = moving_helix.end_basepairs(chosen_end, n_bp=2)

        for bp in fixed_bps_to_trim:
            fixed.trim.update(bp)
        for bp in moving_bps_to_trim:
            moving_helix.trim.update(bp)

        print(f"{prefix} trim: fixed[{fixed.name}] {fixed_end}-end 2 bp (residues={len(fixed_bps_to_trim)*2})")
        print(f"{prefix} trim: helix[{moving_helix.name}] {chosen_end}-end 2 bp (residues={len(moving_bps_to_trim)*2})")

        junctions.append(JunctionInfo(
            jid=junction_id,
            fixed=fixed,
            fixed_end=fixed_end,
            core=core,
            core_end_fixed=core_end_fixed,
            swap_fixed_to_core=swap_fixed,
            next_helix=moving_helix,
            next_end=chosen_end,
            core_end_next=core_end_next,
            swap_next_to_core=swap_next,
        ))

        all_structs.append(core)
        if moving_helix not in all_structs:
            all_structs.append(moving_helix)

    out_path = resolve_output_path(args.out, paths)
    if str(out_path) != str(Path(args.out)):
        print(f"Output path defaulted to the first input folder: {out_path}")
    write_raw_aligned_pdb(structs=all_structs, out_path=raw_output_path(out_path))
    write_ligated_pdb_explicit(structs=all_structs, junctions=junctions, out_path=out_path)


def launch_gui() -> None:
    """Open a small Tkinter GUI for make_BZ parameters."""

    try:
        import tkinter as tk
        from tkinter import filedialog, messagebox, scrolledtext
    except Exception as exc:
        print(f"ERROR: GUI mode requires tkinter, but it could not be imported: {exc}")
        print("Use CLI mode instead, e.g.: python make_BZV2_3.py --axis-mode codirectional --out multi_BZ.pdb B1.pdb Z1.pdb")
        return

    try:
        root = tk.Tk()
    except Exception as exc:
        print(f"ERROR: could not open the Tkinter GUI: {exc}")
        print("Use CLI mode instead, e.g.: python make_BZV2_3.py --axis-mode codirectional --out multi_BZ.pdb B1.pdb Z1.pdb")
        return

    root.title("make_BZ - B/Z junction builder")

    dna_files_var = tk.StringVar()
    out_var = tk.StringVar(value=DEFAULT_OUTPUT_NAME)
    out_default_mode = {"value": True}
    axis_mode_var = tk.StringVar(value="codirectional")
    auto_trim_var = tk.BooleanVar(value=True)
    axis_source_var = tk.StringVar(value="auto")

    frm = tk.Frame(root, padx=10, pady=10)
    frm.grid(row=0, column=0, sticky="nsew")
    root.columnconfigure(0, weight=1)
    root.rowconfigure(0, weight=1)
    frm.columnconfigure(1, weight=1)

    tk.Label(frm, text="DNA input files (must alternate B, Z, B, Z...):").grid(row=0, column=0, columnspan=3, sticky="w")
    files_text = scrolledtext.ScrolledText(frm, width=80, height=7)
    files_text.grid(row=1, column=0, columnspan=3, sticky="nsew", pady=(2, 8))
    frm.rowconfigure(1, weight=1)

    def _input_default_dir() -> str:
        files = [line.strip() for line in files_text.get("1.0", "end").splitlines() if line.strip()]
        if files:
            return str(Path(files[0]).expanduser().resolve().parent)
        return str(Path.cwd())

    def _out_is_default_like() -> bool:
        current = out_var.get().strip()
        if not current:
            return True
        p = Path(current)
        return p.name == DEFAULT_OUTPUT_NAME and out_default_mode["value"]

    def _set_default_output_path(text: str) -> None:
        out_default_mode["value"] = True
        out_var.set(text)

    def _update_default_output_from_inputs() -> None:
        files = [line.strip() for line in files_text.get("1.0", "end").splitlines() if line.strip()]
        if files and _out_is_default_like():
            _set_default_output_path(str(Path(files[0]).expanduser().resolve().parent / DEFAULT_OUTPUT_NAME))

    def add_files() -> None:
        selected = filedialog.askopenfilenames(title="Choose B/Z input PDB files in alternating order")
        if selected:
            current = files_text.get("1.0", "end").strip()
            add_text = "\n".join(selected)
            files_text.delete("1.0", "end")
            files_text.insert("1.0", (current + "\n" + add_text).strip() if current else add_text)
            _update_default_output_from_inputs()

    def clear_files() -> None:
        files_text.delete("1.0", "end")

    tk.Button(frm, text="Add input files...", command=add_files).grid(row=2, column=0, sticky="w")
    tk.Button(frm, text="Clear", command=clear_files).grid(row=2, column=1, sticky="w")

    tk.Label(frm, text="Output PDB:").grid(row=3, column=0, sticky="w", pady=(8, 2))
    out_entry = tk.Entry(frm, textvariable=out_var, width=60)
    out_entry.grid(row=3, column=1, sticky="ew", pady=(8, 2))

    def choose_out() -> None:
        current_out = Path(out_var.get().strip() or DEFAULT_OUTPUT_NAME)
        initialfile = current_out.name or DEFAULT_OUTPUT_NAME
        initialdir = str(current_out.parent) if str(current_out.parent) not in ("", ".") else _input_default_dir()
        selected = filedialog.asksaveasfilename(
            title="Choose output PDB",
            initialdir=initialdir,
            initialfile=initialfile,
            defaultextension=".pdb",
            filetypes=[("PDB files", "*.pdb"), ("All files", "*")],
        )
        if selected:
            out_default_mode["value"] = False
            out_var.set(selected)

    tk.Button(frm, text="Browse...", command=choose_out).grid(row=3, column=2, sticky="e", pady=(8, 2))

    tk.Label(frm, text="Axis correction mode:").grid(row=4, column=0, sticky="w")
    tk.Radiobutton(
        frm,
        text="Co-directional only (default: direction only, no lateral shift)",
        variable=axis_mode_var,
        value="codirectional",
        wraplength=760,
        justify="left",
    ).grid(row=4, column=1, columnspan=2, sticky="w")
    tk.Radiobutton(
        frm,
        text="True collinear (optional strict mode: direction + lateral shift so fitted axis lines coincide)",
        variable=axis_mode_var,
        value="collinear",
        wraplength=760,
        justify="left",
    ).grid(row=5, column=1, columnspan=2, sticky="w")
    tk.Radiobutton(
        frm,
        text="None (no post-fit axis correction)",
        variable=axis_mode_var,
        value="none",
        wraplength=760,
        justify="left",
    ).grid(row=6, column=1, columnspan=2, sticky="w")

    tk.Label(frm, text="Axis source:").grid(row=7, column=0, sticky="w")
    tk.OptionMenu(frm, axis_source_var, "auto", "dssr", "pca").grid(row=7, column=1, sticky="w")
    tk.Label(
        frm,
        text="auto = import align2z.py and use DSSR --more when available; fallback to C1' PCA",
        justify="left",
        wraplength=620,
    ).grid(row=7, column=1, columnspan=2, sticky="w", padx=(90, 0))

    tk.Checkbutton(
        frm,
        text="Auto-trim terminal Z-DNA bp if needed (required for DSSR/bnp_na-generated Z-DNA; input should be 2 bp longer than the target final Z segment)",
        variable=auto_trim_var,
        wraplength=760,
        justify="left",
    ).grid(row=8, column=0, columnspan=3, sticky="w")

    log = scrolledtext.ScrolledText(frm, width=90, height=16)
    log.grid(row=10, column=0, columnspan=3, sticky="nsew", pady=(10, 0))
    frm.rowconfigure(10, weight=2)

    def log_write(text: str) -> None:
        log.insert("end", text)
        log.see("end")
        root.update_idletasks()

    def run_from_gui() -> None:
        files = [line.strip() for line in files_text.get("1.0", "end").splitlines() if line.strip()]
        if len(files) < 2:
            messagebox.showerror("make_BZ", "Please provide at least two files: B1 and Z1.")
            return
        if _out_is_default_like():
            _update_default_output_from_inputs()

        argv = [
            "--out",
            out_var.get().strip() or str(Path(_input_default_dir()) / DEFAULT_OUTPUT_NAME),
            "--axis-mode",
            axis_mode_var.get(),
            "--axis-source",
            axis_source_var.get(),
        ]
        if not auto_trim_var.get():
            argv.append("--no-z-auto-trim")
        argv.extend(files)

        parser = build_arg_parser()
        args = parser.parse_args(argv)

        script_name = Path(sys.argv[0]).name if sys.argv and sys.argv[0] else "make_BZV2_3.py"
        cli_cmd = " ".join(shlex.quote(x) for x in ["python", script_name] + argv)

        import contextlib
        import io
        buf = io.StringIO()
        buf.write("Equivalent CLI command:\n  " + cli_cmd + "\n\n")
        log.delete("1.0", "end")
        try:
            with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(buf):
                run_pipeline(args)
            log_write(buf.getvalue())
            resolved_out = resolve_output_path(args.out, [Path(f) for f in files])
            messagebox.showinfo("make_BZ", f"Done.\nOutput: {resolved_out}\nRaw: {raw_output_path(resolved_out)}")
        except BaseException as exc:
            log_write(buf.getvalue())
            log_write(f"\nERROR: {exc}\n")
            messagebox.showerror("make_BZ", str(exc))

    tk.Button(frm, text="Run make_BZ", command=run_from_gui).grid(row=9, column=0, sticky="w", pady=(10, 0))

    help_text = (
        "Tip: add files in the exact order B1, Z1, B2, Z2...\n"
        "Axis: codirectional is the default (rotation only, no lateral shift). True collinear is optional and may stretch junction contacts.\n"
        "Axis source: auto imports align2z.py and tries DSSR --more first, then falls back to C1' PCA if DSSR is unavailable.\n"
        "Z-DNA requirement: each selected Z chain should start with C/T/U and end with A/G. "
        "The auto-trim option removes at most 1 bp from each Z end to satisfy this requirement. For DSSR/bnp_na-generated Z inputs, prepare the original Z-DNA 2 bp longer than the target final Z segment."
    )
    tk.Label(frm, text=help_text, justify="left", wraplength=760).grid(row=9, column=1, columnspan=2, sticky="w", pady=(10, 0))

    root.mainloop()


def main(argv: Optional[Sequence[str]] = None) -> None:
    if argv is None:
        argv = sys.argv[1:]
    argv = list(argv)
    if len(argv) == 0 or '--gui' in argv:
        launch_gui()
        return
    args = parse_args(argv)
    if not args.dna_files:
        raise SystemExit("ERROR: no DNA input files provided (or run without args for GUI mode).")
    run_pipeline(args)


if __name__ == '__main__':
    main()
