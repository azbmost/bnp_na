@dataclass
class ResidueNode:
    key: ResidKey
    residue: Residue
    P: Optional[np.ndarray]
    O3: Optional[np.ndarray]


def collect_residue_nodes(structs: Sequence[Structure]) -> List[ResidueNode]:
    nodes: List[ResidueNode] = []
    for st in structs:
        for key, res in st.residues.items():
            if key in st.pre_trim or key in st.trim:
                continue
            P = res.xyz('P')  # P is not in alias dict; direct lookup
            if P is None and 'P' in res.atom_by_name:
                rec = res.atom_by_name['P']
                P = np.array([rec.x, rec.y, rec.z], dtype=float)
            O3 = res.xyz("O3'")
            nodes.append(ResidueNode(key=key, residue=res, P=P, O3=O3))
    return nodes


def build_backbone_next(nodes: List[ResidueNode], dist_cutoff: float = 2.2) -> Tuple[Dict[int, int], Dict[int, float]]:
    """Build a mapping i->j meaning residue i's O3' is bonded to residue j's P.

    Returns (next_map, dist_map)
    """
    P_idx = [i for i, n in enumerate(nodes) if n.P is not None]
    O_idx = [i for i, n in enumerate(nodes) if n.O3 is not None]

    if not P_idx or not O_idx:
        raise ValueError("No P atoms or no O3' atoms found; cannot ligate")

    P_coords = np.stack([nodes[i].P for i in P_idx], axis=0)  # (nP,3)

    next_map: Dict[int, int] = {}
    dist_map: Dict[int, float] = {}

    for i in O_idx:
        o = nodes[i].O3
        # Compute distances to all P atoms
        d = np.linalg.norm(P_coords - o[None, :], axis=1)
        # Exclude self if present in P list
        for k, j in enumerate(P_idx):
            if j == i:
                d[k] = np.inf
        kmin = int(np.argmin(d))
        dmin = float(d[kmin])
        if dmin < dist_cutoff:
            j = P_idx[kmin]
            # Ensure unique incoming mapping by keeping the closer one
            if j in next_map.values():
                # Find existing i0 such that next_map[i0]==j
                i0 = next(ii for ii, jj in next_map.items() if jj == j)
                if dmin < dist_map[i0]:
                    next_map.pop(i0)
                    dist_map.pop(i0)
                    next_map[i] = j
                    dist_map[i] = dmin
            else:
                next_map[i] = j
                dist_map[i] = dmin

    return next_map, dist_map


def connected_components_from_next(n_nodes: int, next_map: Dict[int, int]) -> List[List[int]]:
    # Undirected adjacency
    adj: List[List[int]] = [[] for _ in range(n_nodes)]
    for i, j in next_map.items():
        adj[i].append(j)
        adj[j].append(i)

    seen = [False] * n_nodes
    comps: List[List[int]] = []
    for i in range(n_nodes):
        if seen[i]:
            continue
        # BFS
        stack = [i]
        seen[i] = True
        comp = []
        while stack:
            v = stack.pop()
            comp.append(v)
            for w in adj[v]:
                if not seen[w]:
                    seen[w] = True
                    stack.append(w)
        comps.append(comp)
    return comps


def order_component_5to3(comp: List[int], next_map: Dict[int, int]) -> List[int]:
    prev: Dict[int, int] = {}
    for i, j in next_map.items():
        prev[j] = i

    # pick start: node in comp with no prev inside comp
    comp_set = set(comp)
    starts = [i for i in comp if i not in prev or prev[i] not in comp_set]
    if not starts:
        # cycle or ambiguous; fall back
        start = comp[0]
    else:
        start = min(starts)

    order: List[int] = []
    seen = set()
    cur = start
    while cur is not None and cur in comp_set and cur not in seen:
        order.append(cur)
        seen.add(cur)
        cur = next_map.get(cur)

    # If we didn't include all nodes (broken links), append remaining in arbitrary order
    if len(order) != len(comp):
        remaining = [i for i in comp if i not in seen]
        order.extend(sorted(remaining))

    return order


def make_ter_record(chainID: str, resName: str, resSeq: int) -> pdb_ter_record:
    # Serial will be re-numbered by rec2file(reorder_serial=True)
    line = f"TER   {0:5d}      {resName:>3} {chainID}{resSeq:4d}\n"
    return pdb_ter_record(line)




def _core_outer_basepair(core: Structure, core_end: str) -> Tuple[ResidKey, ResidKey]:
    """Return the outermost basepair ResidKeys of a positioned core at the requested end.

    core_end:
      'B' -> outermost B-end bp (E13/F24)
      'Z' -> outermost Z-end bp (E9/F28)

    Returned in the core's internal strand order (E, F).
    """

    if core_end == 'B':
        (a, b) = core_BZ.B_END_BASEPAIRS[-1]
    elif core_end == 'Z':
        (a, b) = core_BZ.Z_END_BASEPAIRS[-1]
    else:
        raise ValueError(f"core_end must be 'B' or 'Z', got {core_end}")

    ka: ResidKey = (core.seg_id, a[0], int(a[1]))
    kb: ResidKey = (core.seg_id, b[0], int(b[1]))
    return ka, kb


def _helix_anchor_basepair(helix: Structure, end: str) -> Tuple[ResidKey, ResidKey]:
    """Return the basepair (ResidKeys) that becomes the helix *anchor* after trimming 2 bp.

    If we trim 2 bp at a given end, the *third* bp from that end is the one that remains
    closest to the junction and is the appropriate residue pair to connect to the core.

    Returned in the helix's internal strand order.
    """

    # Need at least 3 bp to define the anchor.
    bps3 = helix.end_basepairs(end, n_bp=3)
    return bps3[0]



def _add_edge(adj: Dict[ResidKey, set], a: ResidKey, b: ResidKey) -> None:
    adj.setdefault(a, set()).add(b)
    adj.setdefault(b, set()).add(a)


def _distance_min_O3P(resA: Residue, resB: Residue) -> Optional[float]:
    """Return the smaller of O3'(A)->P(B) and O3'(B)->P(A) distances (A)."""

    def P(res: Residue):
        rec = res.atom_by_name.get('P')
        if rec is None:
            return None
        return np.array([rec.x, rec.y, rec.z], dtype=float)

    def O3(res: Residue):
        return res.xyz("O3'")

    PA, PB = P(resA), P(resB)
    OA, OB = O3(resA), O3(resB)
    d = []
    if OA is not None and PB is not None:
        d.append(float(np.linalg.norm(OA - PB)))
    if OB is not None and PA is not None:
        d.append(float(np.linalg.norm(OB - PA)))
    if not d:
        return None
    return min(d)


def build_explicit_backbone_graph(structs: Sequence[Structure], junctions: Sequence[JunctionInfo]) -> Dict[ResidKey, set]:
    """Build an explicit undirected backbone graph using known residue order + junction mapping.

    Why this exists:
      The older approach tried to infer backbone connectivity by global nearest-neighbour O3'-P
      distances. At junctions (and when helices are close in space) that can miss or mis-assign
      links, producing multiple disconnected components.

    Here we:
      1) Add edges within each structure chain by sequence order (resSeq) for the two main chains.
      2) Add 4 edges per junction (2 at fixed-core + 2 at core-next), one per strand.

    The result should be exactly 2 components (2 DNA strands).
    """

    adj: Dict[ResidKey, set] = {}

    # Internal chain edges
    for st in structs:
        for chainID in st.chains:
            keys = [
                k for k, r in st.residues.items()
                if r.chainID == chainID and k not in st.pre_trim and k not in st.trim
            ]
            keys.sort(key=lambda k: st.residues[k].resSeq)
            for k1, k2 in zip(keys, keys[1:]):
                _add_edge(adj, k1, k2)

    # Junction edges
    for jx in junctions:
        fixed_bp = _helix_anchor_basepair(jx.fixed, jx.fixed_end)
        core_bp_fixed = _core_outer_basepair(jx.core, jx.core_end_fixed)

        if not jx.swap_fixed_to_core:
            _add_edge(adj, fixed_bp[0], core_bp_fixed[0])
            _add_edge(adj, fixed_bp[1], core_bp_fixed[1])
        else:
            _add_edge(adj, fixed_bp[0], core_bp_fixed[1])
            _add_edge(adj, fixed_bp[1], core_bp_fixed[0])

        next_bp = _helix_anchor_basepair(jx.next_helix, jx.next_end)
        core_bp_next = _core_outer_basepair(jx.core, jx.core_end_next)

        if not jx.swap_next_to_core:
            _add_edge(adj, next_bp[0], core_bp_next[0])
            _add_edge(adj, next_bp[1], core_bp_next[1])
        else:
            _add_edge(adj, next_bp[0], core_bp_next[1])
            _add_edge(adj, next_bp[1], core_bp_next[0])

    return adj


def connected_components_keys(adj: Dict[ResidKey, set], nodes: List[ResidKey]) -> List[List[ResidKey]]:
    seen = set()
    comps: List[List[ResidKey]] = []
    node_set = set(nodes)

    for n in nodes:
        if n in seen:
            continue
        stack = [n]
        seen.add(n)
        comp = []
        while stack:
            v = stack.pop()
            comp.append(v)
            for w in adj.get(v, set()):
                if w in node_set and w not in seen:
                    seen.add(w)
                    stack.append(w)
        comps.append(comp)

    return comps


def order_path_component_keys(adj: Dict[ResidKey, set], comp: List[ResidKey]) -> List[ResidKey]:
    """Order a component that should represent a simple path (DNA strand)."""

    comp_set = set(comp)
    degrees = {k: len([n for n in adj.get(k, set()) if n in comp_set]) for k in comp}

    ends = [k for k, d in degrees.items() if d == 1]
    if ends:
        start = sorted(ends, key=lambda k: (k[0], k[1], k[2]))[0]
    else:
        start = sorted(comp, key=lambda k: (k[0], k[1], k[2]))[0]

    order: List[ResidKey] = []
    prev = None
    cur = start

    for _ in range(len(comp)):
        order.append(cur)
        neigh = [n for n in adj.get(cur, set()) if n in comp_set and n != prev]
        if not neigh:
            break
        # Deterministic choice if something goes wrong (branching)
        neigh = sorted(neigh, key=lambda k: (k[0], k[1], k[2]))
        nxt = neigh[0]
        prev, cur = cur, nxt

    if len(order) != len(comp):
        remaining = [k for k in comp if k not in set(order)]
        order.extend(sorted(remaining, key=lambda k: (k[0], k[1], k[2])))

    return order


def _p_xyz(res: Residue) -> Optional[np.ndarray]:
    rec = res.atom_by_name.get('P')
    if rec is None:
        return None
    return np.array([rec.x, rec.y, rec.z], dtype=float)


def _o3_xyz(res: Residue) -> Optional[np.ndarray]:
    # alias support handled by Residue.xyz
    return res.xyz("O3'")


def _median(values: List[float]) -> float:
    if not values:
        raise ValueError('median of empty list')
    vals = sorted(values)
    n = len(vals)
    mid = n // 2
    if n % 2 == 1:
        return float(vals[mid])
    return float(0.5 * (vals[mid - 1] + vals[mid]))


def ensure_order_5to3(
    *,
    order: List[ResidKey],
    res_by_key: Dict[ResidKey, Residue],
    verbose_label: str,
) -> List[ResidKey]:
    '''Ensure residue order follows 5'->3' direction.

    We compare typical phosphodiester distances for the proposed order:
        forward:  d(O3'(i) -> P(i+1))
        backward: d(O3'(i+1) -> P(i))

    In a correctly oriented 5'->3' ordering, forward distances should be ~1.6–2.0 A.
    If the backward distances are consistently smaller, we reverse the order.
    '''

    if len(order) < 2:
        return order

    fwd: List[float] = []
    bwd: List[float] = []

    for a_key, b_key in zip(order[:-1], order[1:]):
        a = res_by_key.get(a_key)
        b = res_by_key.get(b_key)
        if a is None or b is None:
            continue
        o3_a = _o3_xyz(a)
        p_a = _p_xyz(a)
        o3_b = _o3_xyz(b)
        p_b = _p_xyz(b)

        if o3_a is not None and p_b is not None:
            fwd.append(float(np.linalg.norm(o3_a - p_b)))
        if o3_b is not None and p_a is not None:
            bwd.append(float(np.linalg.norm(o3_b - p_a)))

    if not fwd or not bwd:
        print(f"{verbose_label} WARNING: cannot determine 5'/3' direction (missing O3'/P). Keeping current order.")
        return order

    # Prefer a robust statistic: use the median of 'bond-like' distances when possible.
    fwd_small = [d for d in fwd if d < 4.0]
    bwd_small = [d for d in bwd if d < 4.0]

    f_stat = _median(fwd_small) if fwd_small else _median(fwd)
    b_stat = _median(bwd_small) if bwd_small else _median(bwd)

    flipped = False
    if b_stat < f_stat:
        order = list(reversed(order))
        flipped = True

    status = "reversed to 5'->3'" if flipped else "kept"

    print(
        f"{verbose_label} strand direction check: median d(O3(i)->P(i+1))={f_stat:.3f} A, "
        f"median d(O3(i+1)->P(i))={b_stat:.3f} A -> {status}"
    )

    return order


def write_ligated_pdb_explicit(
    *,
    structs: Sequence[Structure],
    junctions: Sequence[JunctionInfo],
    out_path: Path,
) -> None:
    """Write final ligated PDB using explicit connectivity (no global nearest-neighbour guessing)."""

    # Gather all kept residues
    res_by_key: Dict[ResidKey, Residue] = {}
    for st in structs:
        for k, r in st.residues.items():
            if k in st.pre_trim or k in st.trim:
                continue
            res_by_key[k] = r

    nodes = sorted(res_by_key.keys(), key=lambda k: (k[0], k[1], k[2]))
    print(f"Total residues after trimming (all segments + cores): {len(nodes)}")

    adj = build_explicit_backbone_graph(structs, junctions)

    # Report junction edge distances for sanity
    for jx in junctions:
        print(f"[J{jx.jid}] explicit bonds (min O3'-P distances):")

        fixed_bp = _helix_anchor_basepair(jx.fixed, jx.fixed_end)
        core_bp_fixed = _core_outer_basepair(jx.core, jx.core_end_fixed)

        pairs_fixed = []
        if not jx.swap_fixed_to_core:
            pairs_fixed = [(fixed_bp[0], core_bp_fixed[0]), (fixed_bp[1], core_bp_fixed[1])]
        else:
            pairs_fixed = [(fixed_bp[0], core_bp_fixed[1]), (fixed_bp[1], core_bp_fixed[0])]

        for a, b in pairs_fixed:
            d = _distance_min_O3P(res_by_key[a], res_by_key[b])
            d_str = f"{d:.3f} A" if d is not None else 'NA'
            print(f"   fixed[{jx.fixed.name}] <-> core[{jx.core.seg_id}] ({a[1]}{a[2]}-{b[1]}{b[2]}): {d_str}")

        next_bp = _helix_anchor_basepair(jx.next_helix, jx.next_end)
        core_bp_next = _core_outer_basepair(jx.core, jx.core_end_next)

        pairs_next = []
        if not jx.swap_next_to_core:
            pairs_next = [(next_bp[0], core_bp_next[0]), (next_bp[1], core_bp_next[1])]
        else:
            pairs_next = [(next_bp[0], core_bp_next[1]), (next_bp[1], core_bp_next[0])]

        for a, b in pairs_next:
            d = _distance_min_O3P(res_by_key[a], res_by_key[b])
            d_str = f"{d:.3f} A" if d is not None else 'NA'
            print(f"   next[{jx.next_helix.name}] <-> core[{jx.core.seg_id}] ({a[1]}{a[2]}-{b[1]}{b[2]}): {d_str}")

    comps = connected_components_keys(adj, nodes)
    comps.sort(key=len, reverse=True)
    print(f"Explicit ligation graph: components={len(comps)} sizes={[len(c) for c in comps]}")

    if len(comps) < 2:
        raise ValueError(f"Explicit ligation expected 2 components (2 strands), found {len(comps)}")

    compA, compB = comps[0], comps[1]

    if len(compA) + len(compB) != len(nodes):
        extra = sum(len(c) for c in comps[2:])
        print(
            f"WARNING: explicit graph produced extra components (extra_residues={extra}). "
            f"They will be appended deterministically to strands."
        )
        toggle = 0
        for c in comps[2:]:
            if toggle == 0:
                compA.extend(c)
            else:
                compB.extend(c)
            toggle = 1 - toggle

    orderA = order_path_component_keys(adj, compA)
    orderB = order_path_component_keys(adj, compB)

    # Ensure both strands are numbered 5'->3' (some components can be discovered in reverse).
    orderA = ensure_order_5to3(order=orderA, res_by_key=res_by_key, verbose_label="[strand A]")
    orderB = ensure_order_5to3(order=orderB, res_by_key=res_by_key, verbose_label="[strand B]")

    print("Final ligation (explicit):")
    print(f"  Strand A residues: {len(orderA)}")
    print(f"  Strand B residues: {len(orderB)}")

    out_recs: List[object] = []

    for chainID, order in [('A', orderA), ('B', orderB)]:
        for new_seq, key in enumerate(order, start=1):
            res = res_by_key[key]
            for a in res.atoms:
                a.update_chainID(chainID)
                a.update_resSeq(new_seq)
            out_recs.extend(res.atoms)

        last_res = res_by_key[order[-1]]
        out_recs.append(make_ter_record(chainID, last_res.resName, len(order)))

    with out_path.open('w') as f:
        rec2file(out_recs, f, reorder_serial=True)
        f.write('END\n')

    print(f"Wrote output PDB: {out_path}")


def write_ligated_pdb(nodes: List[ResidueNode], next_map: Dict[int, int], out_path: Path) -> None:
    comps = connected_components_from_next(len(nodes), next_map)
    comps.sort(key=len, reverse=True)

    if len(comps) < 2:
        raise ValueError(f"Expected 2 backbone components (2 strands), found {len(comps)}")

    # Take the two largest components as the two strands
    compA, compB = comps[0], comps[1]

    orderA = order_component_5to3(compA, next_map)
    orderB = order_component_5to3(compB, next_map)

    print(f"Final ligation: detected {len(comps)} backbone components; using top-2 as strands:")
    print(f"  Strand A residues: {len(orderA)}")
    print(f"  Strand B residues: {len(orderB)}")
    if len(comps) > 2:
        extra = [len(c) for c in comps[2:]]
        print(f"  WARNING: {len(comps)-2} extra small components present (sizes={extra}). They will be ignored.")

    out_recs: List[object] = []

    # Assign chain IDs and renumber residues
    for chainID, order in [('A', orderA), ('B', orderB)]:
        for new_seq, idx in enumerate(order, start=1):
            res = nodes[idx].residue
            # Update all atoms in residue
            for a in res.atoms:
                a.update_chainID(chainID)
                a.update_resSeq(new_seq)
            # Preserve original atom order
            out_recs.extend(res.atoms)
        # TER
        last_res = nodes[order[-1]].residue
        out_recs.append(make_ter_record(chainID, last_res.resName, len(order)))

    with out_path.open('w') as f:
        rec2file(out_recs, f, reorder_serial=True)
        f.write('END\n')

    print(f"Wrote output PDB: {out_path}")


def write_raw_aligned_pdb(*, structs: Sequence[Structure], out_path: Path) -> None:
    '''Write an aligned-but-unligated PDB for inspection.

    This outputs all structures as currently positioned after alignment, before
    junction-overlap trimming and final ligation. Z-DNA residues removed by the
    automatic terminal-phase preprocessing are excluded, because those residues are
    not used during alignment or final assembly.
    '''

    out_recs: List[object] = []
    for st in structs:
        for chainID in st.chains:
            keys = [k for k, r in st.residues.items() if r.chainID == chainID and k not in st.pre_trim]
            keys.sort(key=lambda k: st.residues[k].resSeq)
            if not keys:
                continue
            for key in keys:
                out_recs.extend(st.residues[key].atoms)
            last_res = st.residues[keys[-1]]
            out_recs.append(make_ter_record(chainID, last_res.resName, last_res.resSeq))

    with out_path.open('w') as f:
        rec2file(out_recs, f, reorder_serial=True)
        f.write('END\n')

    print(f"Wrote aligned-raw PDB (no junction trimming/ligation): {out_path}")



