def core_records():
    """Return a *new* list of edit_pdb_atom records for the core BZ junction.

    The returned list contains only ATOM/HETATM/TER records (no ANISOU).
    """
    from edit_pdb_atom import pdb_atom_record, pdb_ter_record
    recs = []
    for ln in PDB_LINES:
        if ln.startswith(("ATOM", "HETATM")):
            recs.append(pdb_atom_record(ln))
        elif ln.startswith("TER"):
            recs.append(pdb_ter_record(ln))
    return recs
